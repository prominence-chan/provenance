#!/usr/bin/env bash
# Merge new upstream Codex into Provenance and prove the fork's hooks survived.
#
#   scripts/sync-upstream.sh                 # fetch openai/codex main, merge, check, build, test
#   scripts/sync-upstream.sh --ref <ref>     # merge a specific upstream ref (e.g. rust-v0.172.0)
#   scripts/sync-upstream.sh --continue      # after resolving the conflicts it left for you
#   scripts/sync-upstream.sh --check         # only run the checks (no fetch / merge)
#
# Options: --no-build (skip cargo build/test/smoke), --full-tests (also the hooked upstream
# crates' own test suites), --remote <name> (default: the remote pointing at openai/codex).
# Env: CARGO_TARGET_DIR (default codex-rs/target), CARGO_JOBS (default 6).
#
# What it does (docs/UPSTREAM.md, "Syncing"):
#   1. fetch upstream main (deepening a shallow clone until the merge base is found)
#   2. `git merge --no-commit` it; resolve the conflicts that have a fixed answer:
#        codex-rs/Cargo.lock         -> upstream's, regenerated by cargo
#        fork-owned paths            -> ours (hooks.toml [owned])
#        files with no fork hook     -> upstream's (the fork does not change them)
#      and stop on files that carry PROVENANCE-HOOK tags, printing what each hook is for
#   3. check every hook is still there (hooks.toml), no conflict markers, and list fork
#      changes that are not in the map
#   4. cargo build the CLI, run `cargo test -p codex-provenance` (the merge guards), and
#      smoke-test `provenance app-server` (model/list must list the tiers; no quota spent)
#   5. commit the merge with a summary
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
HOOKS="codex-rs/provenance/hooks.toml"
REMOTE="" REF="" MODE="sync" BUILD=1 FULL_TESTS=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --ref) REF="$2"; shift 2 ;;
    --remote) REMOTE="$2"; shift 2 ;;
    --continue) MODE="continue"; shift ;;
    --check) MODE="check"; shift ;;
    --no-build) BUILD=0; shift ;;
    --full-tests) FULL_TESTS=1; shift ;;
    -h|--help) sed -n '2,30p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 64 ;;
  esac
done

say() { printf '\033[1m[sync]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[sync]\033[0m %s\n' "$*" >&2; exit 1; }
now() { date +%s; }
T0=$(now)
STATE="$(git rev-parse --git-dir)/PROVENANCE_SYNC"

# ---- hooks.toml helpers (python3 tomllib) -------------------------------------------------
hooks_py() {
  python3 -I - "$HOOKS" "$@" <<'PY'
import fnmatch, sys, tomllib
path, cmd, *rest = sys.argv[1:]
data = tomllib.load(open(path, "rb"))
hooks = {h["file"]: h for h in data["hook"]}
owned = data["owned"]["paths"]
def is_owned(p):
    for pat in owned:
        if pat.endswith("/"):
            if p.startswith(pat): return True
        elif len(pat.split("/")) == len(p.split("/")) and fnmatch.fnmatchcase(p, pat):
            return True
    return False
if cmd == "classify":            # classify FILE... -> "<kind>\t<file>\t<why>"
    for f in rest:
        if f == "codex-rs/Cargo.lock": print(f"lock\t{f}\t")
        elif is_owned(f): print(f"owned\t{f}\t")
        elif f in hooks: print(f"hook\t{f}\t{hooks[f]['why']}")
        else: print(f"other\t{f}\t")
elif cmd == "counts":            # counts -> "<file>\t<expected>"
    for f, h in hooks.items(): print(f"{f}\t{h['count']}")
elif cmd == "mapped":            # mapped FILE... -> files that are neither owned nor hooked
    for f in rest:
        if f != "codex-rs/Cargo.lock" and not is_owned(f) and f not in hooks: print(f)
PY
}

find_remote() {
  [[ -n "$REMOTE" ]] && { echo "$REMOTE"; return; }
  git remote -v | awk '$2 ~ /github\.com[:\/]openai\/codex(\.git)?$/ && $3 == "(fetch)" { print $1; exit }'
}

check_hooks() {
  local bad=0 file want got
  while IFS=$'\t' read -r file want; do
    got=$(grep -o 'PROVENANCE-HOOK' "$file" 2>/dev/null | wc -l | tr -d ' ')
    if [[ "$got" != "$want" ]]; then
      echo "  $file: expected $want PROVENANCE-HOOK tag(s), found $got"; bad=1
    fi
  done < <(hooks_py counts)
  while read -r file; do
    [[ -z "$file" ]] && continue
    echo "  $file: has a PROVENANCE-HOOK tag but is not in $HOOKS"; bad=1
  done < <(hooks_py mapped $(git grep -l 'PROVENANCE-HOOK' -- . ':!ui' || true))
  return $bad
}

run_checks() {
  local upstream="$1" failed=0
  say "checking hooks against $HOOKS"
  if check_hooks; then say "  all hooks present"; else failed=1; fi

  local markers; markers=$(git grep -lE '^(<<<<<<<|>>>>>>>) ' -- codex-rs README.md docs scripts || true)
  if [[ -n "$markers" ]]; then echo "  conflict markers left in:"; sed 's/^/    /' <<<"$markers"; failed=1; fi

  if [[ -n "$upstream" ]]; then
    local unmapped
    unmapped=$(hooks_py mapped $(git diff --name-only "$upstream" -- . ':!ui') | sort -u)
    if [[ -n "$unmapped" ]]; then
      say "  files that differ from upstream but are not in the map (fine if intended; else take upstream's):"
      sed 's/^/    /' <<<"$unmapped"
    fi
  fi
  [[ $failed == 0 ]] || die "hook check failed: fix the files above (docs/UPSTREAM.md, 'Resolving a hook conflict')"

  [[ $BUILD == 1 ]] || { say "skipping build/test/smoke (--no-build)"; return; }
  export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/codex-rs/target}"
  local jobs="${CARGO_JOBS:-6}" t
  t=$(now); say "cargo build -p codex-cli --bin provenance (target $CARGO_TARGET_DIR)"
  (cd codex-rs && cargo build -p codex-cli --bin provenance -j "$jobs") || die "build failed"
  say "  built in $(( $(now) - t ))s"
  t=$(now); say "cargo test -p codex-provenance (merge guards)"
  (cd codex-rs && cargo test -p codex-provenance -j "$jobs") || die "hook tests failed (see output; docs/UPSTREAM.md)"
  say "  tests passed in $(( $(now) - t ))s"
  if [[ $FULL_TESTS == 1 ]]; then
    say "cargo test for the hooked upstream crates"
    (cd codex-rs && cargo test -j "$jobs" -p codex-models-manager -p codex-model-provider-info \
      -p codex-utils-home-dir -p codex-arg0) || say "  some upstream tests failed: check whether they assert upstream defaults the fork changes"
  fi
  local tiers; tiers=$(python3 -I -c 'import tomllib,sys; print(",".join(t["slug"] for t in tomllib.load(open(sys.argv[1],"rb"))["tiers"]))' codex-rs/provenance/harness.toml)
  say "smoke: provenance app-server, model/list must start with $tiers"
  python3 -I scripts/provenance-smoke.py "$CARGO_TARGET_DIR/debug/provenance" --expect-tiers "$tiers" || die "smoke test failed"
}

# ---- --check ------------------------------------------------------------------------
if [[ "$MODE" == "check" ]]; then
  # Compare with the last upstream commit merged into HEAD.
  R=$(find_remote); U="${REF:-${R:+$R/main}}"
  if git rev-parse -q --verify "$U^{commit}" >/dev/null; then U=$(git merge-base HEAD "$U" || true); else U=""; fi
  run_checks "$U"; say "done in $(( $(now) - T0 ))s"; exit 0
fi

# ---- sync: fetch + merge -------------------------------------------------------------
if [[ "$MODE" == "sync" ]]; then
  git diff --quiet && git diff --cached --quiet || die "tracked changes in the working tree; commit or stash first (or use a worktree)"
  [[ -f "$(git rev-parse --git-dir)/MERGE_HEAD" ]] && die "a merge is in progress; resolve it and run with --continue"
  R=$(find_remote); [[ -n "$R" ]] || die "no remote points at github.com/openai/codex; pass --remote"
  if [[ -z "$REF" ]]; then
    say "fetching $R main"
    git fetch "$R" "+refs/heads/main:refs/remotes/$R/main"
    REF="$R/main"
  else
    git rev-parse -q --verify "$REF^{commit}" >/dev/null || git fetch "$R" "$REF" || true
  fi
  UP=$(git rev-parse "$REF^{commit}")
  if ! git merge-base HEAD "$UP" >/dev/null 2>&1; then
    [[ "$(git rev-parse --is-shallow-repository)" == "true" ]] || die "HEAD and $REF share no history"
    for depth in 200 1000 5000; do
      say "shallow clone: deepening by $depth to find the merge base"
      git fetch --deepen="$depth" "$R" "+refs/heads/main:refs/remotes/$R/main" >/dev/null 2>&1 || true
      git merge-base HEAD "$UP" >/dev/null 2>&1 && break
    done
    git merge-base HEAD "$UP" >/dev/null 2>&1 || die "still no merge base; try: git fetch --unshallow $R"
  fi
  BASE=$(git merge-base HEAD "$UP")
  say "merging $REF ($(git log -1 --format='%h %cd' --date=short "$UP")): $(git rev-list --count "$BASE..$UP") upstream commits since $(git log -1 --format=%h "$BASE")"
  T_MERGE=$(now)
  set +e
  git -c rerere.enabled=true -c merge.conflictStyle=diff3 merge --no-ff --no-commit "$UP" >/dev/null 2>&1
  set -e
  [[ -f "$(git rev-parse --git-dir)/MERGE_HEAD" ]] || { say "already up to date with $REF"; exit 0; }
  CONFLICTS=$(git diff --name-only --diff-filter=U)
  N_ALL=$(grep -c . <<<"$CONFLICTS" || true)
  say "git reported $N_ALL conflicted file(s)"
  NEED=()
  while IFS=$'\t' read -r kind file why; do
    [[ -z "$file" ]] && continue
    case "$kind" in
      lock)  git checkout --theirs -- "$file" && git add -- "$file"; say "  auto  $file: upstream's (cargo regenerates it)" ;;
      owned) git checkout --ours -- "$file" && git add -- "$file"; say "  auto  $file: fork-owned, kept ours" ;;
      other)
        if git show ":2:$file" 2>/dev/null | grep -q 'PROVENANCE-HOOK'; then
          NEED+=("$file"); say "  YOU   $file: has a hook tag but is missing from hooks.toml"
        else
          git checkout --theirs -- "$file" 2>/dev/null && git add -- "$file" || git rm -q -- "$file"
          say "  auto  $file: no fork hook, took upstream's"
        fi ;;
      hook)  NEED+=("$file"); say "  YOU   $file: $why" ;;
    esac
  done < <(hooks_py classify $CONFLICTS)
  printf '%s\n' "$UP" "$N_ALL" "${#NEED[@]}" "$T_MERGE" > "$STATE"
  if [[ ${#NEED[@]} -gt 0 ]]; then
    say ""
    say "${#NEED[@]} file(s) with fork hooks need you. For each:"
    say "  1. take upstream's side of every conflict block"
    say "  2. re-apply the fork's PROVENANCE-HOOK line(s), as they were before:"
    for f in "${NEED[@]}"; do say "       git show ORIG_HEAD:$f | grep -n -B3 -A3 PROVENANCE-HOOK"; done
    say "  3. git add <file>; then: scripts/sync-upstream.sh --continue"
    say "docs/UPSTREAM.md lists every hook and why it exists."
    exit 2
  fi
fi

# ---- continue: everything resolved ------------------------------------------------------
[[ -f "$(git rev-parse --git-dir)/MERGE_HEAD" ]] || die "no merge in progress"
[[ -z "$(git diff --name-only --diff-filter=U)" ]] || die "unresolved files left: $(git diff --name-only --diff-filter=U | tr '\n' ' ')"
read -r UP N_ALL N_NEED T_MERGE < <(tr '\n' ' ' < "$STATE"; echo)
say "merge resolved in $(( $(now) - T_MERGE ))s ($N_ALL conflicted file(s), $N_NEED needed a person)"
say "refreshing codex-rs/Cargo.lock (upstream's lock + the fork's crate)"
(cd codex-rs && cargo metadata --format-version 1 >/dev/null) && git add codex-rs/Cargo.lock
# Checks run against the merged index; build/test/smoke use the working tree.
git diff --quiet || git add -u -- codex-rs README.md docs scripts
run_checks "$UP"
git add -u -- codex-rs
git commit -q --no-verify -F - <<EOF
Merge upstream openai/codex $(git log -1 --format=%h "$UP") into Provenance

Upstream: $(git log -1 --format='%H (%cd)' --date=short "$UP")
Conflicted files: $N_ALL ($N_NEED needed a person; the rest resolved by
scripts/sync-upstream.sh: Cargo.lock regenerated, fork-owned paths kept,
files without fork hooks taken from upstream).
Checks: hooks.toml hook counts, cargo build, cargo test -p codex-provenance,
app-server model/list smoke.
EOF
rm -f "$STATE"
say "committed $(git log -1 --format=%h): sync took $(( $(now) - T0 ))s in this run"
say "install: (cd codex-rs && cargo build --release -p codex-cli --bin provenance -j 4) && install -m 755 codex-rs/target/release/provenance ~/.local/bin/provenance"
say "then, if the protocol changed: (cd ui && npm run gen:protocol)"
